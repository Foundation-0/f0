#!/usr/bin/env python3
"""quotient_anchor_kernel.py — Executable Single-Thread Kernel
Across Foundation-0 (gravity, project-asma, exoplanets-frontier), Moissanite-Labs (weft),
ahrazzle/soko, and Proven-Commons.

Corrected 2026-11-15 against ahrazzle's review of f0#41. The original kernel
printed a hardcoded "5/5 domains verified" over six hashed results, used
`assert` (removed under `python3 -O`), checked only `c` for the weft and
exoplanet witnesses, and let an empty edge list certify a floor. All of that
is fixed below; the essay quotes the corrected receipt.

What this kernel is: six result objects (project-asma inversion, weft
inversion, fold-rank concordance, trapping fraction, four-node bound,
exoplanet inversion) plus one negative control (the p = 0 confound), each
computed from synthetic inputs generated by the same model the check then
inverts. A passing run shows the algebra is self-consistent. It does not show
that any cited repository's data fits the model, and it reads no repository.
Proven-Commons is named in the essay and in this docstring but no check here
calls it.

The digest covers the six result objects only, exactly as the original file
hashed them, so the digest is unchanged by this correction
(`8ff47efe0a8d2885a59af396cf9f001ad41314359d2ccc1a6f0cda85c53ff1a5`).
The confound control is verified but not hashed. The success line computes its
check and domain counts from the checks that ran; a named domain with no check
is printed as not exercised. The kernel fails if its recomputed receipt differs
from `kernel-output.txt` next to this file.
"""

from __future__ import annotations

from fractions import Fraction
import hashlib
import json
import os
import sys
from typing import Callable, Dict, List, Optional, Sequence, Tuple


class WitnessFailure(RuntimeError):
    """Raised when a kernel check does not hold. Never disabled by `python -O`."""


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise WitnessFailure(message)


# Domains the essay and this docstring name. The receipt line reports which of
# these the checks actually exercised; a named domain with no check is printed
# as not exercised, never counted as verified.
NAMED_DOMAINS = (
    "Foundation-0/gravity",
    "Foundation-0/project-asma",
    "Foundation-0/exoplanets-frontier",
    "Moissanite-Labs/weft",
    "ahrazzle/soko",
    "Proven-Commons",
)


def verify_anchored_mobius_certificate(
    domain: str,
    alpha_null_anchor: Fraction,
    p_low: Fraction,
    y_low: Fraction,
    p_high: Fraction,
    y_high: Fraction,
) -> Dict[str, str]:
    """Recover `(r, c)` from two mixtures after deflating bleed `alpha`.

    `alpha` must come from an independent `c = 0` control read on the same
    channel. The sample's own `p = 0` endpoint is not an anchor: there
    `y(0) = alpha + (1 - alpha) * c`, so conversion looks like bleed (with
    `alpha = 3/20` and `c = 1/4`, `y(0) = 29/80`, and using that endpoint as
    the anchor returns `c = 0`; see the confound control in `main`).
    """
    _require(
        Fraction(0, 1) <= alpha_null_anchor < Fraction(1, 1),
        f"anchor alpha {alpha_null_anchor} outside [0, 1)",
    )
    _require(
        Fraction(0, 1) < p_low < p_high < Fraction(1, 1),
        "requires 0 < p_low < p_high < 1",
    )
    q_low = (y_low - alpha_null_anchor) / (1 - alpha_null_anchor)
    q_high = (y_high - alpha_null_anchor) / (1 - alpha_null_anchor)
    _require(
        Fraction(0, 1) <= q_low < 1 and Fraction(0, 1) <= q_high < 1,
        f"deflated fraction outside [0, 1): {q_low}, {q_high}",
    )
    phi_low = (1 - p_low) / (1 - q_low)
    phi_high = (1 - p_high) / (1 - q_high)
    slope = (phi_high - phi_low) / (p_high - p_low)
    intercept = phi1_0 = phi_low - slope * p_low
    _require(intercept > 0, f"non-positive survival intercept {intercept}")
    c_conv = 1 - Fraction(1, 1) / phi1_0
    r_amp = 1 + slope / phi1_0
    return {
        "domain": domain,
        "alpha_anchor": str(alpha_null_anchor),
        "Phi_intercept": str(intercept),
        "Phi_slope": str(slope),
        "c_conversion_or_synthesis": str(c_conv),
        "r_selection_or_snr": str(r_amp),
    }


def verify_shift_quotient_concordance(
    folds: Sequence[Tuple[Sequence[Fraction], Sequence[Fraction]]],
) -> Dict[str, str]:
    within_n = 0
    fold_aucs: List[Fraction] = []
    raw_pos, raw_neg, cal_pos, cal_neg = [], [], [], []
    for pos_k, neg_k in folds:
        u_k = sum(
            Fraction(1, 1) if x > y else (Fraction(1, 2) if x == y else Fraction(0, 1))
            for x in pos_k for y in neg_k
        )
        within_n += len(pos_k) * len(neg_k)
        fold_aucs.append(u_k / (len(pos_k) * len(neg_k)))
        raw_pos.extend(pos_k)
        raw_neg.extend(neg_k)
        comb = list(pos_k) + list(neg_k)
        m = Fraction(len(comb), 1)
        for x in pos_k:
            cal_pos.append((Fraction(sum(1 for z in comb if z < x), 1) + Fraction(sum(1 for z in comb if z == x), 2)) / m)
        for y in neg_k:
            cal_neg.append((Fraction(sum(1 for z in comb if z < y), 1) + Fraction(sum(1 for z in comb if z == y), 2)) / m)

    def pair_auc(ps: Sequence[Fraction], ns: Sequence[Fraction]) -> Fraction:
        u = sum(Fraction(1, 1) if x > y else (Fraction(1, 2) if x == y else Fraction(0, 1)) for x in ps for y in ns)
        return u / (len(ps) * len(ns))

    return {
        "fold_mean_auc": str(sum(fold_aucs, Fraction(0, 1)) / len(fold_aucs)),
        "raw_pooled_auc": str(pair_auc(raw_pos, raw_neg)),
        "midrank_calibrated_auc": str(pair_auc(cal_pos, cal_neg)),
        "within_pair_fraction": str(Fraction(within_n, len(raw_pos) * len(raw_neg))),
    }


def verify_quotient_conservation_bound(
    concrete_edges: Sequence[Tuple[int, int, int]],
    quotient_h: Dict[int, int],
    s0: int,
    goal_states: Sequence[int],
    successors: Optional[Callable[[int], Sequence[Tuple[int, int]]]] = None,
) -> Dict[str, object]:
    """Fail-closed quotient lower bound on a toy graph (not a soko room).

    Raises ValueError on an empty goal set or on any state that appears in an
    edge, as the start, or as a goal without an `h` value. Raises
    WitnessFailure when a goal has non-zero `h`, when any supplied edge
    violates `h(u) <= cost + h(v)`, when no goal is reachable from the start
    over the supplied edges, or — when `successors` is given (the true
    transition function) — when any transition reachable from the start is
    missing from the edge list. Without `successors` the bound holds only if
    the supplied edges cover every transition reachable from the start.
    """
    if not goal_states:
        raise ValueError("Goal set must be non-empty.")
    if s0 not in quotient_h:
        raise ValueError(f"Start state {s0} has no h value.")
    for g in goal_states:
        if g not in quotient_h:
            raise ValueError(f"Goal state {g} has no h value.")
        _require(quotient_h[g] == 0, f"goal state {g} has non-zero h={quotient_h[g]}")
    violations = 0
    for u, v, cost in concrete_edges:
        if u not in quotient_h or v not in quotient_h:
            raise ValueError(f"Edge ({u}, {v}) uses a state with no h value.")
        if quotient_h[u] > cost + quotient_h[v]:
            violations += 1
    _require(violations == 0, f"{violations} Bellman violation(s) on supplied edges")
    reachable: set = set()
    stack = [s0]
    while stack:
        u = stack.pop()
        if u in reachable:
            continue
        reachable.add(u)
        for (a, b, _c) in concrete_edges:
            if a == u:
                stack.append(b)
    _require(
        bool(reachable & set(goal_states)),
        "no goal reachable from start over the supplied edges",
    )
    if successors is not None:
        edge_set = {(u, v, cost) for u, v, cost in concrete_edges}
        closed: set = set()
        stack = [s0]
        while stack:
            u = stack.pop()
            if u in closed:
                continue
            closed.add(u)
            for v, cost in successors(u):
                _require(
                    (u, v, cost) in edge_set,
                    f"reachable transition ({u}, {v}, {cost}) missing from supplied edges",
                )
                stack.append(v)
    return {"certified_lower_bound": quotient_h[s0], "edges_checked": len(concrete_edges), "bellman_violations": violations}


def run_checks() -> str:
    """Run every check and return the receipt line. Raises WitnessFailure on the first miss."""
    # (domain, check name); a check is recorded only after its _require calls pass.
    checks: List[Tuple[str, str]] = []

    def obs_y(p: Fraction, r: Fraction, c: Fraction, alpha: Fraction) -> Fraction:
        q = (r * p + c * (1 - p)) / (r * p + (1 - p))
        return (1 - alpha) * q + alpha

    asma = verify_anchored_mobius_certificate(
        "Foundation-0/project-asma", Fraction(3, 20),
        Fraction(1, 20), obs_y(Fraction(1, 20), Fraction(11, 1), Fraction(1, 4), Fraction(3, 20)),
        Fraction(3, 8), obs_y(Fraction(3, 8), Fraction(11, 1), Fraction(1, 4), Fraction(3, 20)),
    )
    _require(
        asma["c_conversion_or_synthesis"] == "1/4" and asma["r_selection_or_snr"] == "11",
        f"project-asma recovery gave c={asma['c_conversion_or_synthesis']}, r={asma['r_selection_or_snr']}",
    )
    checks.append(("Foundation-0/project-asma", "project-asma inversion"))

    weft = verify_anchored_mobius_certificate(
        "Moissanite-Labs/weft", Fraction(2, 5),
        Fraction(1, 20), obs_y(Fraction(1, 20), Fraction(8, 1), Fraction(0, 1), Fraction(2, 5)),
        Fraction(3, 8), obs_y(Fraction(3, 8), Fraction(8, 1), Fraction(0, 1), Fraction(2, 5)),
    )
    _require(
        weft["c_conversion_or_synthesis"] == "0" and weft["r_selection_or_snr"] == "8",
        f"weft recovery gave c={weft['c_conversion_or_synthesis']}, r={weft['r_selection_or_snr']}",
    )
    checks.append(("Moissanite-Labs/weft", "weft inversion"))

    shift = verify_shift_quotient_concordance([
        ([Fraction(12, 1), Fraction(11, 1)], [Fraction(9, 1), Fraction(8, 1)]),
        ([Fraction(2, 1), Fraction(1, 1)], [Fraction(-1, 1), Fraction(-2, 1)]),
    ])
    _require(
        shift["fold_mean_auc"] == "1" and shift["raw_pooled_auc"] == "3/4" and shift["midrank_calibrated_auc"] == "1",
        f"fold-rank concordance gave {shift}",
    )
    checks.append(("Foundation-0/project-asma", "fold-rank concordance"))

    sigma_halo_sq = Fraction(177 * 177, 1)
    f_trap_z608 = 1 - Fraction(97, 100) ** 2 / sigma_halo_sq
    f_trap_z0 = max(Fraction(0, 1), 1 - Fraction(18559, 100) ** 2 / sigma_halo_sq)
    _require(
        f_trap_z608 > Fraction(9999, 10000) and f_trap_z0 == 0,
        f"trapping fractions are {f_trap_z608}, {f_trap_z0}",
    )
    checks.append(("Foundation-0/gravity", "trapping fraction"))

    # Four-node toy graph (not a soko room). The successor function is the
    # toy graph's complete transition function, so closure is checked.
    toy_successors = {0: [(1, 1), (2, 2)], 1: [(2, 1)], 2: [(3, 1)], 3: []}
    soko = verify_quotient_conservation_bound(
        [(0, 1, 1), (1, 2, 1), (0, 2, 2), (2, 3, 1)],
        {0: 3, 1: 2, 2: 1, 3: 0}, 0, [3],
        successors=lambda u: toy_successors.get(u, []),
    )
    _require(soko["certified_lower_bound"] == 3, f"toy bound is {soko['certified_lower_bound']}")
    checks.append(("ahrazzle/soko", "four-node bound"))

    exo = verify_anchored_mobius_certificate(
        "Foundation-0/exoplanets-frontier", Fraction(1, 10),
        Fraction(1, 10), obs_y(Fraction(1, 10), Fraction(9, 1), Fraction(0, 1), Fraction(1, 10)),
        Fraction(1, 2), obs_y(Fraction(1, 2), Fraction(9, 1), Fraction(0, 1), Fraction(1, 10)),
    )
    _require(
        exo["c_conversion_or_synthesis"] == "0" and exo["r_selection_or_snr"] == "9",
        f"exoplanet recovery gave c={exo['c_conversion_or_synthesis']}, r={exo['r_selection_or_snr']}",
    )
    checks.append(("Foundation-0/exoplanets-frontier", "exoplanet inversion"))

    # Negative control for the p = 0 confound: the sample's own p = 0 endpoint
    # (y(0) = 29/80 with alpha = 3/20, c = 1/4) used as the anchor erases the
    # conversion. This behaviour is required here so the confound is on the
    # record; the control is verified, not hashed into the digest.
    confound = verify_anchored_mobius_certificate(
        "p = 0 confound (negative control)", Fraction(29, 80),
        Fraction(1, 20), obs_y(Fraction(1, 20), Fraction(11, 1), Fraction(1, 4), Fraction(3, 20)),
        Fraction(3, 8), obs_y(Fraction(3, 8), Fraction(11, 1), Fraction(1, 4), Fraction(3, 20)),
    )
    _require(
        confound["c_conversion_or_synthesis"] == "0" and confound["r_selection_or_snr"] == "11",
        f"p = 0 confound gave c={confound['c_conversion_or_synthesis']}, r={confound['r_selection_or_snr']}",
    )
    checks.append(("Foundation-0/project-asma", "p = 0 confound control"))

    digest = hashlib.sha256(json.dumps([asma, weft, shift, str(f_trap_z608), soko, exo], sort_keys=True).encode()).hexdigest()
    # The receipt counts the checks that ran and the domains they exercised; no
    # count on this line is a literal.
    n_checks = len(checks)
    domains = sorted({domain for domain, _name in checks})
    not_exercised = [name for name in NAMED_DOMAINS if name not in domains]
    return (
        f"SINGLE_THREAD_KERNEL_OK: {n_checks}/{n_checks} checks passed | {len(domains)} domains | "
        f"{', '.join(not_exercised)} not exercised | SHA-256: {digest}"
    )


def main() -> int:
    try:
        line = run_checks()
    except WitnessFailure as exc:
        print(f"SINGLE_THREAD_KERNEL_FAILED | {exc}", file=sys.stderr)
        return 1
    except ValueError as exc:
        print(f"SINGLE_THREAD_KERNEL_FAILED | {exc}", file=sys.stderr)
        return 1
    print(line)
    receipt = os.path.join(os.path.dirname(os.path.abspath(__file__)), "kernel-output.txt")
    try:
        with open(receipt, encoding="utf-8") as fh:
            recorded = fh.read().strip()
    except FileNotFoundError:
        recorded = None
    if recorded is not None and recorded != line:
        print(
            "SINGLE_THREAD_KERNEL_FAILED | recomputed receipt differs from kernel-output.txt; "
            "regenerate it from this run",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
